"""
REST API (Django REST Framework). Interactive docs at /api/docs/ (Swagger, generated by drf-spectacular).

POST /api/v1/predict     pollutant readings -> PM2.5, AQI, category, drivers, optional explanation
GET  /api/v1/history     past predictions, paginated (staff only)
GET  /api/v1/stats       historical averages (?year=&month=), or the dashboard summary
GET  /api/v1/live        current Delhi readings (Open-Meteo), cached 10 minutes, with fallback
POST /api/v1/live        the same for given coordinates {"lat": .., "lon": ..}
GET  /api/v1/report      live AQI for central Delhi; POST {"lat", "lon", "label"} for any place
GET  /api/v1/places      search places by name (?q=)
GET  /api/v1/measures    what to do at an AQI level (?aqi=&profile=), or all six categories
POST /api/v1/ask         question -> answer with sources (RAG + data tools)

All endpoints are throttled per client (60/min, the assistant 10/min) because the
assistant can call a paid LLM API.
"""
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import OpenApiParameter, extend_schema
from rest_framework import generics, permissions, status
from rest_framework.response import Response
from rest_framework.throttling import ScopedRateThrottle
from rest_framework.views import APIView

from core import assistant, measures, naqi, stats
from core.report import ReportError

from . import services
from .models import Prediction
from .serializers import AskSerializer, LocationSerializer, PredictInputSerializer, PredictionSerializer


class PredictView(APIView):
    @extend_schema(request=PredictInputSerializer, responses={200: OpenApiTypes.OBJECT, 400: OpenApiTypes.OBJECT},
                   summary="Estimate PM2.5 and India's AQI from pollutant readings")
    def post(self, request):
        s = PredictInputSerializer(data=request.data)
        s.is_valid(raise_exception=True)
        d = s.validated_data
        values = {k: d[k] for k in ("co", "no", "no2", "o3", "so2", "pm10", "nh3")}
        try:
            result = services.run_prediction(values, source=Prediction.Source.API, profile=d["profile"], explain=d["explain"])
        except ValueError as e:
            return Response({"error": str(e)}, status=status.HTTP_400_BAD_REQUEST)
        return Response(result)


class HistoryView(generics.ListAPIView):
    queryset = Prediction.objects.all()
    serializer_class = PredictionSerializer
    permission_classes = [permissions.IsAdminUser]  # other people's readings are not public

    @extend_schema(summary="Past predictions, newest first (staff only)")
    def get(self, request, *args, **kwargs):
        return super().get(request, *args, **kwargs)


class StatsView(APIView):
    @extend_schema(summary="Historical PM2.5 statistics for Delhi",
                   parameters=[OpenApiParameter("year", int, required=False), OpenApiParameter("month", int, required=False)],
                   responses=OpenApiTypes.OBJECT)
    def get(self, request):
        year, month = request.query_params.get("year"), request.query_params.get("month")
        try:
            year = int(year) if year else None
            month = int(month) if month else None
        except ValueError:
            return Response({"error": "year and month must be integers"}, status=status.HTTP_400_BAD_REQUEST)
        if month is not None and not 1 <= month <= 12:
            return Response({"error": "month must be 1-12"}, status=status.HTTP_400_BAD_REQUEST)
        if year is None and month is None:
            d = services.dashboard_data()
            return Response({k: d[k] for k in ("coverage", "overall_mean", "month_of_year", "category_share", "worst_days")})
        result = stats.monthly_average(year, month)
        return Response(result, status=status.HTTP_404_NOT_FOUND if "error" in result else status.HTTP_200_OK)


class LiveView(APIView):
    @extend_schema(summary="Current pollutant readings for central Delhi (Open-Meteo), cached for 10 minutes",
                   responses=OpenApiTypes.OBJECT)
    def get(self, request):
        return Response(services.live_readings())

    @extend_schema(request=LocationSerializer, responses=OpenApiTypes.OBJECT,
                   summary="Current pollutant readings for given coordinates (e.g. the browser's location)")
    def post(self, request):
        # Coordinates arrive in the request body, not the URL, so they don't end up in server logs.
        s = LocationSerializer(data=request.data)
        s.is_valid(raise_exception=True)
        return Response(services.live_readings(s.validated_data["lat"], s.validated_data["lon"]))


class ReportView(APIView):
    """Live AQI report: CPCB-style averages, pollutants, 24-hour outlook and the best time to go out."""

    def _respond(self, lat=None, lon=None, label=None):
        try:
            return Response(services.live_report(lat, lon, label))
        except ReportError as e:
            return Response({"error": str(e)}, status=status.HTTP_502_BAD_GATEWAY)

    @extend_schema(summary="Live AQI report for central Delhi", responses=OpenApiTypes.OBJECT)
    def get(self, request):
        return self._respond()

    @extend_schema(request=LocationSerializer, responses=OpenApiTypes.OBJECT,
                   summary="Live AQI report for given coordinates (sent in the body, not the URL)")
    def post(self, request):
        s = LocationSerializer(data=request.data)
        s.is_valid(raise_exception=True)
        d = s.validated_data
        return self._respond(d["lat"], d["lon"], d.get("label"))


class PlacesView(APIView):
    @extend_schema(summary="Search places by name (Open-Meteo geocoding), Indian results first",
                   parameters=[OpenApiParameter("q", str, required=True)], responses=OpenApiTypes.OBJECT)
    def get(self, request):
        return Response({"results": services.search_places(request.query_params.get("q", ""))})


class MeasuresView(APIView):
    @extend_schema(summary="What to do at an AQI level: personal measures (MoHFW) and GRAP stage measures (CAQM)",
                   parameters=[OpenApiParameter("aqi", int, required=False, description="0-500; omit for all six categories"),
                               OpenApiParameter("profile", str, required=False, description="general, children, elderly, lung_heart, pregnant, outdoor_worker")],
                   responses=OpenApiTypes.OBJECT)
    def get(self, request):
        profile = request.query_params.get("profile", "general")
        if profile not in assistant.PROFILES:
            return Response({"error": f"profile must be one of {', '.join(assistant.PROFILES)}"}, status=status.HTTP_400_BAD_REQUEST)
        aqi = request.query_params.get("aqi")
        if aqi is None:
            return Response({"categories": measures.table()})
        try:
            aqi = float(aqi)
        except ValueError:
            return Response({"error": "aqi must be a number"}, status=status.HTTP_400_BAD_REQUEST)
        if not 0 <= aqi <= 500:
            return Response({"error": "aqi must be between 0 and 500"}, status=status.HTTP_400_BAD_REQUEST)
        return Response(measures.for_aqi(aqi, profile))


class AskView(APIView):
    throttle_classes = [ScopedRateThrottle]
    throttle_scope = "assistant"

    @extend_schema(request=AskSerializer, responses=OpenApiTypes.OBJECT,
                   summary="Ask the assistant (answers cite their sources; says when it doesn't know)")
    def post(self, request):
        s = AskSerializer(data=request.data)
        s.is_valid(raise_exception=True)
        return Response(assistant.ask(s.validated_data["question"]))
